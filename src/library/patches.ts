export const PATCH_BY_ID: Record<string, LibraryPatch> = Object.fromEntries(PATCH_LIBRARY.map((p) => [p.id, p]));

export function patchesForRole(role: LibraryPatch["role"]): LibraryPatch[] {
  return PATCH_LIBRARY.filter((p) => p.role === role);
}

export function searchPatches(query: string): LibraryPatch[] {
  const q = query.toLowerCase().split(/[\s,]+/).filter(Boolean);
  return PATCH_LIBRARY.filter((p) => q.every((t) => p.id.includes(t) || p.role.includes(t) || p.tags.some((x) => x.includes(t)) || p.reference.toLowerCase().includes(t)));
}
